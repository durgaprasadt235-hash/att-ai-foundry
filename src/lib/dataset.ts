// Bring-your-own-dataset (BYOD) — upload a dataset file and test with it.
//
// The first-call problem: a director will NOT connect live company data
// into someone else's working environment on a first call, and wiring a
// live connection takes days to weeks. So the first call runs on a sample
// file the director's team brings: upload it here, validate it, test with
// it in minutes. No live connection, nothing leaves the browser.
//
// Two formats:
//   (a) JSON — one file, same shape as test-data.json / server/seed.json:
//       { customers, ledger, usage, tickets?, cases, docs?, orders?,
//         stairTrees? }. Missing optional tables default to [].
//   (b) CSV — one file per table, by filename: customers.csv, ledger.csv,
//       usage.csv, cases.csv, tickets.csv (optional). Policy docs and
//       STAIR trees are JSON-only (their bodies contain commas and
//       structure a flat CSV cannot express honestly).
//
// Validation rules D1–D12 — the Python mirror (server/validate_dataset.py)
// implements the SAME rules with the SAME numbering, so a file that passes
// here passes there. Validation is a PRE-CHECK, not a gate: a file with
// errors is NOT rejected. It is accepted raw and cleansed automatically
// (see lib/cleanse.ts — Bronze → Silver): balances are recomputed from
// the ledger, unfixable records are quarantined and listed, and the
// cleansed file is what loads. The validator itself never rewrites
// anything; the cleanser fixes and LISTS every correction. Warnings
// never block a load, but they are shown.
//
//   D1  Top level is an object; customers, ledger, usage, cases are
//       present arrays. Optional tables default to [].
//   D2  At least 1 customer.
//   D3  Ids unique within each table; STAIR leaf ids unique across trees.
//   D4  Required fields present with the right type (strings non-empty
//       where an id/name is concerned; numbers finite).
//   D5  Enums: customer status active|suspended|closed; ledger kind
//       charge|credit|payment, status posted|reversed; case type in the
//       7 engine types; case status in the 6 statuses (missing → 'open',
//       listed as filled); usage numbers >= 0.
//   D6  Every ledger / usage / ticket / case customerId must reference a
//       known customer id. Unknown references are errors, not warnings.
//   D7  Balance reconciliation: for each customer, the sum of POSTED
//       ledger amounts must equal the stated balance within $0.01.
//       Amounts are positive magnitudes — kind decides the sign:
//       charge adds, credit and payment subtract (see signedLedgerAmount).
//       A mismatch is an error and is LISTED. The validator never
//       rewrites a balance; the cleanser (lib/cleanse.ts) corrects it
//       on load — ledger is the source of truth — and records the
//       correction in the cleansing report.
//   D8  Case amount: warning when no posted ledger entry for that
//       customer has the same amount — the case may still run and fail
//       honestly, but the director should know before the call.
//   D9  Duplicate charges: warning listing pairs found (same customer,
//       same service, same amount, within 7 days, different invoice).
//       Duplicates are expected test content — they drive the billing
//       journey — so they warn, they do not block.
//   D10 Zero-amount ledger entries: warning (the Silver gate quarantines
//       them; they contribute $0.00 to reconciliation).
//   D11 Suspended customer with balance > 0: warning (Silver quarantines).
//   D12 File size: JSON text over 5 MB is rejected (guard against
//       accidentally uploading a production dump).
//
// Filled fields are transparent, never silent: anything auto-filled
// (case status, idempotencyKey, createdAt, ticket status, doc updated,
// stair-tree autoGenerated) is listed in the report.
