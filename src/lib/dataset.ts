export const DATASET_MAX_BYTES = 5_000_000;

/** The one ledger-sign rule, used by D7 and by Medallion Gold totals.
// Amounts in a file are positive magnitudes; kind decides the sign:
// a charge adds to what the customer owes, a credit or a payment
// subtracts. A negative amount in the file is taken as given (so a
// negative payment would add) — the rule is the kind, not the sign. */
export function signedLedgerAmount(e: Pick<LedgerEntry, 'amount' | 'kind'>): number {
  const amount = typeof e.amount === 'number' && Number.isFinite(e.amount) ? e.amount : 0;
  return e.kind === 'charge' ? amount : -amount;
}

export const CASE_TYPES = ['duplicate_charge', 'plan_change', 'roaming_dispute', 'provisioning', 'outage', 'retention', 'other'] as const;
export const CASE_STATUSES = ['open', 'running', 'awaiting_approval', 'resolved', 'failed', 'rejected'] as const;

export interface DatasetTables {
  customers: Customer[];
  ledger: LedgerEntry[];
  usage: UsageRecord[];
  tickets: Ticket[];
  cases: Case[];
  docs: PolicyDoc[];
  orders: AppState['orders'];
  stairTrees: StairTree[];
}

export interface BalanceMismatch {
  customerId: string;
  name: string;
  stated: number;
  computed: number;
}

export interface DatasetValidation {
  valid: boolean;
  errors: string[];
  warnings: string[];
  counts: { customers: number; ledger: number; usage: number; tickets: number; cases: number; docs: number; orders: number; stairTrees: number };
  duplicatesFound: string[];
  balanceMismatches: BalanceMismatch[];
  unmatchedCases: string[];
  /** Fields auto-filled during load — listed, never silent. */
  filled: string[];
}

const isObj = (v: unknown): v is Record<string, unknown> => typeof v === 'object' && v !== null && !Array.isArray(v);
const isNonEmptyStr = (v: unknown): v is string => typeof v === 'string' && v.trim().length > 0;
const isFiniteNum = (v: unknown): v is number => typeof v === 'number' && Number.isFinite(v);
const moneyEq = (a: number, b: number): boolean => Math.abs(a - b) < 0.005;

/** Same duplicate rule as the engine (src/lib/engine.ts findDuplicate):
 *  same customer, same service, same amount, within 7 days, different
 *  invoice, posted charges only. */
export function findDuplicatePairs(ledger: LedgerEntry[]): { customerId: string; original: LedgerEntry; duplicate: LedgerEntry }[] {
  const pairs: { customerId: string; original: LedgerEntry; duplicate: LedgerEntry }[] = [];
  const byCustomer = new Map<string, LedgerEntry[]>();
  for (const e of ledger) {
    if (e.kind !== 'charge' || e.status !== 'posted') continue;
    const list = byCustomer.get(e.customerId) ?? [];
    list.push(e);
    byCustomer.set(e.customerId, list);
  }
  for (const [customerId, charges] of byCustomer) {
    const sorted = [...charges].sort((a, b) => a.date.localeCompare(b.date));
    for (let i = 0; i < sorted.length; i++) {
      for (let j = i + 1; j < sorted.length; j++) {
        const a = sorted[i];
        const b = sorted[j];
        if (a.service !== b.service || a.amount !== b.amount || a.invoice === b.invoice) continue;
        const days = (new Date(b.date).getTime() - new Date(a.date).getTime()) / 86400000;
        if (days >= 0 && days <= 7) pairs.push({ customerId, original: a, duplicate: b });
      }
    }
  }
  return pairs;
}

function emptyValidation(): DatasetValidation {
  return {
    valid: false, errors: [], warnings: [],
    counts: { customers: 0, ledger: 0, usage: 0, tickets: 0, cases: 0, docs: 0, orders: 0, stairTrees: 0 },
    duplicatesFound: [], balanceMismatches: [], unmatchedCases: [], filled: [],
  };
}

/** Validate parsed JSON data. Returns the validation plus, when valid,
 *  the normalised tables (defaults applied, filled fields listed).
 *  `rawTables` is the parsed tables whenever the file is structurally
 *  sound (D1 passed) — even when validation fails. The cleanser
 *  (lib/cleanse.ts) starts from rawTables; `tables` stays null unless
 *  the file is valid, so existing callers are unaffected. */
export function validateDatasetJson(data: unknown): { validation: DatasetValidation; tables: DatasetTables | null; rawTables: DatasetTables | null } {
  const v = emptyValidation();
  if (!isObj(data)) {
    v.errors.push('D1: dataset must be a JSON object with customers, ledger, usage and cases arrays.');
    return { validation: v, tables: null, rawTables: null };
  }
  const tables: DatasetTables = {
    customers: [], ledger: [], usage: [], tickets: [], cases: [], docs: [], orders: [], stairTrees: [],
  };
  // D1 — required tables present and arrays; optional tables default [].
  for (const key of ['customers', 'ledger', 'usage', 'cases'] as const) {
    if (!Array.isArray(data[key])) {
      v.errors.push(`D1: "${key}" is missing or not an array — it is required.`);
    } else {
      tables[key] = data[key] as never;
    }
  }
  for (const key of ['tickets', 'docs', 'orders', 'stairTrees'] as const) {
    if (data[key] === undefined) continue;
    if (!Array.isArray(data[key])) {
      v.errors.push(`D1: "${key}" must be an array when present.`);
    } else {
      tables[key] = data[key] as never;
    }
  }
  if (v.errors.length > 0) return { validation: v, tables: null, rawTables: null };

  // D2 — at least one customer.
  if (tables.customers.length === 0) v.errors.push('D2: dataset has no customers — at least 1 is required.');

  // D3 — unique ids within each table.
  const checkUnique = (rows: { id?: unknown }[], label: string) => {
    const seen = new Set<string>();
    for (const r of rows) {
      if (!isNonEmptyStr(r.id)) continue;
      if (seen.has(r.id)) v.errors.push(`D3: duplicate id "${r.id}" in ${label}.`);
      seen.add(r.id);
    }
  };
  checkUnique(tables.customers, 'customers');
  checkUnique(tables.ledger, 'ledger');
  checkUnique(tables.usage, 'usage');
  checkUnique(tables.tickets, 'tickets');
  checkUnique(tables.cases, 'cases');
  checkUnique(tables.docs, 'docs');
  checkUnique(tables.stairTrees, 'stairTrees');
  const leafIds = new Set<string>();
  for (const t of tables.stairTrees) {
    if (!Array.isArray((t as unknown as Record<string, unknown>).leaves)) {
      v.errors.push(`D3: stair tree "${(t as { id?: unknown }).id ?? '?'}" has no leaves array.`);
      continue;
    }
    for (const leaf of t.leaves) {
      if (!isNonEmptyStr(leaf.id)) continue;
      if (leafIds.has(leaf.id)) v.errors.push(`D3: duplicate STAIR leaf id "${leaf.id}" across trees.`);
      leafIds.add(leaf.id);
    }
  }

  const customerIds = new Set(tables.customers.map((c) => c.id));

  // D4 + D5 — required fields, types, enums.
  for (const c of tables.customers) {
    if (!isNonEmptyStr(c.id)) v.errors.push('D4: a customer is missing a non-empty "id".');
    if (!isNonEmptyStr(c.name)) v.errors.push(`D4: customer ${c.id ?? '?'} is missing "name".`);
    if (!isNonEmptyStr(c.account)) v.errors.push(`D4: customer ${c.id ?? '?'} is missing "account".`);
    if (!isNonEmptyStr(c.plan)) v.errors.push(`D4: customer ${c.id ?? '?'} is missing "plan".`);
    if (!isFiniteNum(c.balance)) v.errors.push(`D4: customer ${c.id ?? '?'} has a non-numeric "balance".`);
    if (!['active', 'suspended', 'closed'].includes(c.status)) v.errors.push(`D5: customer ${c.id ?? '?'} has unknown status ${JSON.stringify(c.status)} (use active|suspended|closed).`);
    if (!isNonEmptyStr(c.since)) v.errors.push(`D4: customer ${c.id ?? '?'} is missing "since".`);
  }
  for (const e of tables.ledger) {
    if (!isNonEmptyStr(e.id)) v.errors.push('D4: a ledger entry is missing a non-empty "id".');
    if (!isNonEmptyStr(e.customerId)) v.errors.push(`D4: ledger ${e.id ?? '?'} is missing "customerId".`);
    if (!isNonEmptyStr(e.invoice)) v.errors.push(`D4: ledger ${e.id ?? '?'} is missing "invoice".`);
    if (!isNonEmptyStr(e.service)) v.errors.push(`D4: ledger ${e.id ?? '?'} is missing "service".`);
    if (!isFiniteNum(e.amount)) v.errors.push(`D4: ledger ${e.id ?? '?'} has a non-numeric "amount".`);
    if (!['charge', 'credit', 'payment'].includes(e.kind)) v.errors.push(`D5: ledger ${e.id ?? '?'} has unknown kind ${JSON.stringify(e.kind)} (use charge|credit|payment).`);
    if (!['posted', 'reversed'].includes(e.status)) v.errors.push(`D5: ledger ${e.id ?? '?'} has unknown status ${JSON.stringify(e.status)} (use posted|reversed).`);
  }
  for (const u of tables.usage) {
    if (!isNonEmptyStr(u.id)) v.errors.push('D4: a usage record is missing a non-empty "id".');
    if (!isNonEmptyStr(u.customerId)) v.errors.push(`D4: usage ${u.id ?? '?'} is missing "customerId".`);
    if (!isNonEmptyStr(u.month)) v.errors.push(`D4: usage ${u.id ?? '?'} is missing "month".`);
    for (const f of ['dataGb', 'minutes', 'sms'] as const) {
      if (!isFiniteNum(u[f])) v.errors.push(`D4: usage ${u.id ?? '?'} has a non-numeric "${f}".`);
      else if ((u[f] as number) < 0) v.errors.push(`D5: usage ${u.id ?? '?'} has a negative "${f}" (${u[f]}).`);
    }
  }
  for (const t of tables.tickets) {
    if (!isNonEmptyStr(t.id)) v.errors.push('D4: a ticket is missing a non-empty "id".');
    if (!isNonEmptyStr(t.customerId)) v.errors.push(`D4: ticket ${t.id ?? '?'} is missing "customerId".`);
    if (!isNonEmptyStr(t.subject)) v.errors.push(`D4: ticket ${t.id ?? '?'} is missing "subject".`);
    if (t.status !== undefined && !['open', 'resolved'].includes(t.status)) v.errors.push(`D5: ticket ${t.id ?? '?'} has unknown status ${JSON.stringify(t.status)} (use open|resolved).`);
  }
  for (const c of tables.cases) {
    if (!isNonEmptyStr(c.id)) v.errors.push('D4: a case is missing a non-empty "id".');
    if (!isNonEmptyStr(c.customerId)) v.errors.push(`D4: case ${c.id ?? '?'} is missing "customerId".`);
    if (!CASE_TYPES.includes(c.type as never)) v.errors.push(`D5: case ${c.id ?? '?'} has unknown type ${JSON.stringify(c.type)} (use ${CASE_TYPES.join('|')}).`);
    if (!isNonEmptyStr(c.title)) v.errors.push(`D4: case ${c.id ?? '?'} is missing "title".`);
    if (!isFiniteNum(c.amount)) v.errors.push(`D4: case ${c.id ?? '?'} has a non-numeric "amount".`);
  }
  for (const d of tables.docs) {
    if (!isNonEmptyStr(d.id)) v.errors.push('D4: a policy doc is missing a non-empty "id".');
    if (!isNonEmptyStr(d.title)) v.errors.push(`D4: doc ${d.id ?? '?'} is missing "title".`);
    if (!isNonEmptyStr(d.body)) v.errors.push(`D4: doc ${d.id ?? '?'} is missing "body".`);
  }
  for (const t of tables.stairTrees) {
    if (!isNonEmptyStr(t.id)) v.errors.push('D4: a STAIR tree is missing a non-empty "id".');
    if (!isNonEmptyStr(t.title)) v.errors.push(`D4: stair tree ${t.id ?? '?'} is missing "title".`);
    for (const leaf of t.leaves ?? []) {
      if (!isNonEmptyStr(leaf.id) || !isNonEmptyStr(leaf.title) || !isNonEmptyStr(leaf.path) || !isNonEmptyStr(leaf.body)) {
        v.errors.push(`D4: a STAIR leaf in tree ${t.id ?? '?'} is missing id/title/path/body.`);
      }
    }
  }

  // D6 — references must resolve.
  for (const e of tables.ledger) {
    if (isNonEmptyStr(e.customerId) && !customerIds.has(e.customerId)) v.errors.push(`D6: ledger ${e.id} references unknown customer ${e.customerId}.`);
  }
  for (const u of tables.usage) {
    if (isNonEmptyStr(u.customerId) && !customerIds.has(u.customerId)) v.errors.push(`D6: usage ${u.id} references unknown customer ${u.customerId}.`);
  }
  for (const t of tables.tickets) {
    if (isNonEmptyStr(t.customerId) && !customerIds.has(t.customerId)) v.errors.push(`D6: ticket ${t.id} references unknown customer ${t.customerId}.`);
  }
  for (const c of tables.cases) {
    if (isNonEmptyStr(c.customerId) && !customerIds.has(c.customerId)) v.errors.push(`D6: case ${c.id} references unknown customer ${c.customerId}.`);
  }

  // D7 — balance reconciliation (posted entries only; amounts are
  // positive magnitudes, kind decides the sign — see signedLedgerAmount).
  for (const c of tables.customers) {
    if (!isFiniteNum(c.balance)) continue;
    const computed = tables.ledger
      .filter((e) => e.customerId === c.id && e.status === 'posted')
      .reduce((s, e) => s + signedLedgerAmount(e), 0);
    if (Math.abs(computed - c.balance) >= 0.01) {
      v.balanceMismatches.push({ customerId: c.id, name: c.name, stated: c.balance, computed: Math.round(computed * 100) / 100 });
      v.errors.push(`D7: balance does not reconcile for ${c.id} (${c.name}): stated $${c.balance.toFixed(2)}, ledger sums to $${computed.toFixed(2)}. The cleanser corrects the balance to $${computed.toFixed(2)} on load (ledger is the source of truth) — see the cleansing report.`);
    }
  }

  // D8 — case amount with no matching ledger entry (warning only).
  for (const c of tables.cases) {
    if (!isFiniteNum(c.amount) || !isNonEmptyStr(c.customerId)) continue;
    const match = tables.ledger.some((e) => e.customerId === c.customerId && e.status === 'posted' && moneyEq(e.amount, c.amount));
    if (!match) {
      v.unmatchedCases.push(c.id);
      v.warnings.push(`D8: case ${c.id} amount $${c.amount.toFixed(2)} matches no posted ledger entry for ${c.customerId} — the agent may fail honestly when run.`);
    }
  }

  // D9 — duplicate charges found (warning only; they drive the billing journey).
  for (const p of findDuplicatePairs(tables.ledger)) {
    const label = `${p.customerId}: ${p.original.invoice} + ${p.duplicate.invoice} ($${p.duplicate.amount.toFixed(2)})`;
    v.duplicatesFound.push(label);
    v.warnings.push(`D9: duplicate charge found — ${label}.`);
  }

  // D10 — zero-amount ledger entries (warning; Silver quarantines them).
  for (const e of tables.ledger) {
    if (e.amount === 0) v.warnings.push(`D10: ledger ${e.id} has a zero amount (Silver will quarantine it).`);
  }
  // D11 — suspended customer with a balance (warning; Silver quarantines).
  for (const c of tables.customers) {
    if (c.status === 'suspended' && isFiniteNum(c.balance) && c.balance > 0) {
      v.warnings.push(`D11: suspended customer ${c.id} (${c.name}) still has a balance of $${c.balance.toFixed(2)} (Silver will quarantine it).`);
    }
  }

  // Transparent fills (listed, never silent).
  for (const c of tables.cases) {
    if (!c.status || !CASE_STATUSES.includes(c.status as never)) {
      c.status = 'open';
      v.filled.push(`case ${c.id}: status set to "open" (was missing/unknown).`);
    }
    if (!isNonEmptyStr(c.idempotencyKey)) {
      c.idempotencyKey = `${c.id.toLowerCase()}-v1`;
      v.filled.push(`case ${c.id}: idempotencyKey set to "${c.idempotencyKey}".`);
    }
    if (!isNonEmptyStr(c.createdAt)) {
      c.createdAt = new Date().toISOString();
      v.filled.push(`case ${c.id}: createdAt set to now.`);
    }
  }
  for (const t of tables.tickets) {
    if (!t.status) { t.status = 'open'; v.filled.push(`ticket ${t.id}: status set to "open".`); }
    if (!isNonEmptyStr(t.date)) { t.date = new Date().toISOString().slice(0, 10); v.filled.push(`ticket ${t.id}: date set to today.`); }
  }
  for (const d of tables.docs) {
    if (!isNonEmptyStr(d.updated)) { d.updated = new Date().toISOString().slice(0, 10); v.filled.push(`doc ${d.id}: updated set to today.`); }
  }
  for (const t of tables.stairTrees) {
    if (t.autoGenerated === undefined) { t.autoGenerated = false; v.filled.push(`stair tree ${t.id}: autoGenerated set to false (uploaded trees are treated as authored).`); }
    for (const leaf of t.leaves ?? []) {
      if (!isNonEmptyStr(leaf.section)) { leaf.section = ''; v.filled.push(`STAIR leaf ${leaf.id}: section left blank.`); }
    }
  }

  v.counts = {
    customers: tables.customers.length, ledger: tables.ledger.length, usage: tables.usage.length,
    tickets: tables.tickets.length, cases: tables.cases.length, docs: tables.docs.length,
    orders: tables.orders.length, stairTrees: tables.stairTrees.length,
  };
  v.valid = v.errors.length === 0;
  return { validation: v, tables: v.valid ? tables : null, rawTables: tables };
}

/* ---------------- CSV ----------------
 * One file per table, matched by filename stem (customers.csv, ledger.csv,
 * usage.csv, cases.csv, tickets.csv). Headers are documented in
 * docs/DATASET_GUIDE.md and in csvHeaders() below. Policy docs and STAIR
 * trees are JSON-only. */

export const CSV_HEADERS: Record<string, string[]> = {
  customers: ['id', 'name', 'account', 'phone', 'email', 'plan', 'status', 'since', 'balance', 'city'],
  ledger: ['id', 'customerId', 'invoice', 'date', 'service', 'amount', 'kind', 'status'],
  usage: ['id', 'customerId', 'month', 'dataGb', 'minutes', 'sms'],
  cases: ['id', 'customerId', 'type', 'title', 'description', 'amount', 'status', 'createdAt', 'idempotencyKey'],
  tickets: ['id', 'customerId', 'date', 'subject', 'status'],
};

/** Minimal CSV parser: quoted fields, embedded commas, CRLF, doubled
 *  quotes. Throws on unbalanced quotes. */
export function parseCsv(text: string): { headers: string[]; rows: Record<string, string>[] } {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = '';
  let inQuotes = false;
  const pushField = () => { row.push(field); field = ''; };
  const pushRow = () => { pushField(); rows.push(row); row = []; };
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (inQuotes) {
      if (ch === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; } else { inQuotes = false; }
      } else { field += ch; }
    } else if (ch === '"') {
      inQuotes = true;
    } else if (ch === ',') {
      pushField();
    } else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i++;
      pushRow();
    } else {
      field += ch;
    }
  }
  if (inQuotes) throw new Error('Unbalanced quotes in CSV — a quoted field was never closed.');
  if (field.length > 0 || row.length > 0) pushRow();
  const nonEmpty = rows.filter((r) => r.some((c) => c.trim() !== ''));
  if (nonEmpty.length === 0) throw new Error('CSV file is empty.');
  const headers = nonEmpty[0].map((h) => h.trim());
  return {
    headers,
    rows: nonEmpty.slice(1).map((r) => {
      const obj: Record<string, string> = {};
      headers.forEach((h, idx) => { obj[h] = (r[idx] ?? '').trim(); });
      return obj;
    }),
  };
}

const csvNum = (raw: string, label: string, errors: string[]): number | null => {
  if (raw === '') { errors.push(`D4: ${label} is missing a numeric value.`); return null; }
  const n = Number(raw);
  if (!Number.isFinite(n)) { errors.push(`D4: ${label} is not a number (${JSON.stringify(raw)}).`); return null; }
  return n;
};

/** Assemble a dataset from CSV files ({ filename, text }[]). Returns the
 *  same validation shape as validateDatasetJson. `rawTables` is the
 *  assembled data whenever the CSVs parsed and all required tables are
 *  present — even when a row has a bad number (the cleanser quarantines
 *  that row). It is null only when the CSVs are structurally unusable
 *  (unrecognised file, missing header, missing required table). */
export function datasetFromCsvFiles(files: { name: string; text: string }[]): { validation: DatasetValidation; tables: DatasetTables | null; rawTables: DatasetTables | null } {
  const v = emptyValidation();
  const byTable = new Map<string, Record<string, string>[]>();
  for (const f of files) {
    const stem = f.name.replace(/\.csv$/i, '').split('/').pop()?.toLowerCase() ?? '';
    if (!CSV_HEADERS[stem]) {
      v.errors.push(`CSV: unrecognised file "${f.name}" — expected one of ${Object.keys(CSV_HEADERS).map((k) => `${k}.csv`).join(', ')}.`);
      continue;
    }
    try {
      const parsed = parseCsv(f.text);
      const expected = CSV_HEADERS[stem];
      const missing = expected.filter((h) => !parsed.headers.includes(h));
      if (missing.length > 0) {
        v.errors.push(`CSV: ${f.name} is missing header column(s): ${missing.join(', ')}. Expected: ${expected.join(', ')}.`);
        continue;
      }
      byTable.set(stem, parsed.rows);
    } catch (e) {
      v.errors.push(`CSV: ${f.name} could not be parsed — ${e instanceof Error ? e.message : String(e)}`);
    }
  }
  for (const required of ['customers', 'ledger', 'usage', 'cases']) {
    if (!byTable.has(required)) v.errors.push(`D1: "${required}.csv" was not uploaded — customers, ledger, usage and cases are all required.`);
  }
  if (v.errors.length > 0) return { validation: v, tables: null, rawTables: null };

  const data: Record<string, unknown> = {
    customers: (byTable.get('customers') ?? []).map((r) => ({
      id: r.id, name: r.name, account: r.account, phone: r.phone, email: r.email,
      plan: r.plan, status: r.status, since: r.since,
      balance: csvNum(r.balance, `customer ${r.id || '?'} balance`, v.errors), city: r.city,
    })),
    ledger: (byTable.get('ledger') ?? []).map((r) => ({
      id: r.id, customerId: r.customerId, invoice: r.invoice, date: r.date, service: r.service,
      amount: csvNum(r.amount, `ledger ${r.id || '?'} amount`, v.errors), kind: r.kind, status: r.status,
    })),
    usage: (byTable.get('usage') ?? []).map((r) => ({
      id: r.id, customerId: r.customerId, month: r.month,
      dataGb: csvNum(r.dataGb, `usage ${r.id || '?'} dataGb`, v.errors),
      minutes: csvNum(r.minutes, `usage ${r.id || '?'} minutes`, v.errors),
      sms: csvNum(r.sms, `usage ${r.id || '?'} sms`, v.errors),
    })),
    cases: (byTable.get('cases') ?? []).map((r) => ({
      id: r.id, customerId: r.customerId, type: r.type, title: r.title, description: r.description,
      amount: csvNum(r.amount, `case ${r.id || '?'} amount`, v.errors),
      status: r.status || undefined, createdAt: r.createdAt || undefined, idempotencyKey: r.idempotencyKey || undefined,
    })),
    tickets: (byTable.get('tickets') ?? []).map((r) => ({
      id: r.id, customerId: r.customerId, date: r.date, subject: r.subject, status: r.status || undefined,
    })),
    docs: [], orders: [], stairTrees: [],
  };
  // A bad number leaves a null in the assembled row (csvNum records the
  // D4 error above). The row is still handed to the cleanser as raw
  // material — it quarantines the row and lists it, instead of the whole
  // file being unusable.
  if (v.errors.length > 0) return { validation: v, tables: null, rawTables: data as unknown as DatasetTables };
  return validateDatasetJson(data);
}

/* ---------------- Loading ---------------- */

/** Build a fresh working state from validated tables. Runs, pipeline runs,
 *  evals and notifications start empty — the new dataset is a fresh
 *  caseload. The built-in seed files on disk are never touched.
 *  `cleanseSummary` is passed when the tables came out of the cleanser
 *  (lib/cleanse.ts) — it is recorded in the audit entry so the load is
 *  traceable to its corrections and quarantines. */
export function datasetToState(tables: DatasetTables, name: string, cleanseSummary?: string): AppState {
  const seed = seedState();
  const now = new Date().toISOString();
  return {
    customers: tables.customers,
    ledger: tables.ledger,
    usage: tables.usage,
    tickets: tables.tickets,
    cases: tables.cases,
    runs: [],
    docs: tables.docs,
    orders: tables.orders,
    stairTrees: tables.stairTrees,
    pipelines: seed.pipelines,
    pipelineRuns: [],
    evalRuns: [],
    audit: [{
      id: `AUD-${Date.now().toString(36)}`, at: now, actor: 'system', action: cleanseSummary ? 'dataset_cleansed' : 'dataset_loaded', operatorId: getCurrentOperatorId(),
      detail: `Loaded dataset "${name}": ${tables.customers.length} customers, ${tables.ledger.length} ledger entries, ${tables.usage.length} usage records, ${tables.cases.length} cases. Previous caseload replaced; built-in seed untouched.${cleanseSummary ? ` ${cleanseSummary}` : ''}`,
    }],
    notifications: [],
    events: [],
    seededAt: now,
    datasetName: name,
    datasetSource: 'uploaded',
  };
}

/** Serialise tables back to the production-ready JSON file — the same
 *  shape as test-data.json / server/seed.json, so the cleansed file can
 *  be handed to the fulfilment team or used as a new seed. */
export function datasetTablesToJson(tables: DatasetTables): string {
  return JSON.stringify({
    customers: tables.customers,
    ledger: tables.ledger,
    usage: tables.usage,
    tickets: tables.tickets,
    cases: tables.cases,
    docs: tables.docs,
    orders: tables.orders,
    stairTrees: tables.stairTrees,
  }, null, 2);
}

/** Serialise one CSV table from cleansed tables — same headers and
 *  quoting as the CSV templates, so the file round-trips through the
 *  CSV upload path. Docs and STAIR trees are JSON-only. */
export function datasetTableToCsv(table: keyof typeof CSV_HEADERS, tables: DatasetTables): string {
  const headers = CSV_HEADERS[table];
  const rows = ((tables as unknown as Record<string, unknown[]>)[table] ?? []) as Record<string, unknown>[];
  const lines = [headers.join(',')];
  for (const row of rows) {
    lines.push(headers.map((h) => csvCell(row[h] == null ? '' : row[h] as string | number)).join(','));
  }
  return lines.join('\n') + '\n';
}

