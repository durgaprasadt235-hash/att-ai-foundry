function csvCell(v: string | number): string {
  const s = String(v);
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

/** CSV template for one table, built from the same example data as the
 *  JSON template so a team can start from either format. */
export function templateCsv(table: keyof typeof CSV_HEADERS): string {
  const parsed = JSON.parse(templateDatasetJson()) as Record<string, Record<string, unknown>[]>;
  const headers = CSV_HEADERS[table];
  const lines = [headers.join(',')];
  for (const row of parsed[table] ?? []) {
    lines.push(headers.map((h) => csvCell((row[h] as string | number | undefined) ?? '')).join(','));
  }
  return lines.join('\n') + '\n';
}
