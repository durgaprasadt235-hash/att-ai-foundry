// STAIR — STructure Aware Information Retriever (IBM Research, Kumar et al.,
// arXiv 2609.03874). Implemented here as described in the paper, in plain code:
//
//  * No chunking, no embeddings, no vector database. Knowledge docs are stored
//    as structured trees: a Table of Contents, sections, and leaf nodes.
//    No vector DB by design: STAIR needs none — retrieval navigates a TOC,
//    it does not search an embedding space. The adapter interface where
//    embeddings would plug in, if the fulfilment team ever wants them, is
//    stairRetrieve() below: replace its token-overlap scoring with an
//    embedding lookup over the same leaf titles, keep the allowlist, and
//    the contract (only a TOC leaf may be returned) is unchanged.
//  * Retrieval is given the FULL Table of Contents and navigates to the exact
//    leaf section. The answer comes ONLY from that leaf, retrieved intact.
//  * Constrained selection: the retriever may only return a leaf title that
//    exists in the TOC. The valid titles are held in an allowlist (a trie in
//    the Python implementation, a Set here). It cannot invent a section —
//    by construction the invalid-section rate is 0 on the seeded eval set.
//  * Docs without a TOC: a TOC is auto-generated from headings and flagged
//    as auto-generated; if no heading/section matches, the answer is
//    "not found in policy" instead of a guess.
//
// Honest numbers (from the paper, with the paper's own definition):
//  * Hallucination < 0.05% in the paper means generating an INVALID SECTION
//    IDENTIFIER — not "the answer was wrong". Do not read it as general
//    factual accuracy.
//  * Recall@1 on SearchTome: STAIR 82.6%, DSI 76.9%, DPR 68.7%, BM25 59.5%.
//  * The "65x reduction" figure is NOT stated as a verified fact anywhere
//    in this app.
//  * Our own measured Recall@1 / invalid-section rate on the seeded eval set
//    is computed live in the UI (see measureStairEval) — that is the number
//    that matters for this demo.
import type { PolicyDoc, StairLeaf, StairTree } from './types';
import { tokenize } from './text'; // text.ts, not engine.ts — importing engine here created a cycle (see text.ts)

export interface StairHit {
  leaf: StairLeaf;
  score: number;
  matched: string[];
}

/** The valid-leaf allowlist: only these titles may ever be returned. */
export function validLeafTitles(trees: StairTree[]): Set<string> {
  return new Set(trees.flatMap((t) => t.leaves.map((l) => l.title)));
}

export function allLeaves(trees: StairTree[]): StairLeaf[] {
  return trees.flatMap((t) => t.leaves);
}

/** Navigate the full TOC to the best-matching leaf. No chunking: the leaf is
 *  scored on its path + title, and returned intact. */
export function stairRetrieve(trees: StairTree[], query: string): StairHit | null {
  const q = [...new Set(tokenize(query))];
  if (q.length === 0) return null;
  const allowed = validLeafTitles(trees);
  let best: StairHit | null = null;
  for (const leaf of allLeaves(trees)) {
    if (!allowed.has(leaf.title)) continue; // constrained selection — cannot happen, enforced
    const hay = tokenize(`${leaf.path} ${leaf.title} ${leaf.section}`);
    const matched = q.filter((t) => hay.includes(t));
    const score = matched.length / q.length;
    if (score >= 0.2 && (!best || score > best.score)) best = { leaf, score: Math.round(score * 100) / 100, matched };
  }
  return best;
}

export function stairAnswer(trees: StairTree[], query: string): { answer: string; leaf: StairLeaf | null; score: number; refused: boolean } {
  const hit = stairRetrieve(trees, query);
  if (!hit) {
    return { answer: 'Not found in policy — no section in the Table of Contents matches this question, so I will not guess.', leaf: null, score: 0, refused: true };
  }
  return { answer: hit.leaf.body, leaf: hit.leaf, score: hit.score, refused: false };
}

/** Auto-generate a TOC for a plain doc with no headings: one section per
 *  sentence group, flagged autoGenerated. Used only as a fallback. */
export function autoTocFromDoc(doc: PolicyDoc): StairTree {
  const sentences = doc.body.split(/(?<=[.!?])\s+/).filter(Boolean);
  const leaves: StairLeaf[] = sentences.map((s, i) => ({
    id: `${doc.id}-AUTO-${i + 1}`,
    title: `${doc.title} — auto section ${i + 1}`,
    path: `${doc.title} > Auto-generated > Section ${i + 1}`,
    section: `§A.${i + 1}`,
    body: s,
  }));
  return { id: doc.id, title: doc.title, autoGenerated: true, leaves };
}

