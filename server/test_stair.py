"""Pytest unit tests for STAIR (server/stair_retriever.py).

Covers: valid-leaf-only retrieval, intact section retrieval, no chunking
(the leaf body is returned whole, never split), not-found handling, and
the auto-generated TOC fallback.
Run: python3 -m pytest server/test_stair.py -v
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

from stair_retriever import (  # noqa: E402
    TitleTrie,
    answer,
    auto_toc_from_doc,
    measure_eval,
    retrieve,
    valid_titles,
)


def load_trees():
    seed = json.loads((Path(__file__).parent / "seed.json").read_text())
    return seed["stairTrees"]


def test_retrieval_returns_only_a_valid_leaf():
    trees = load_trees()
    hit = retrieve(trees, "duplicate charge credit policy")
    assert hit is not None
    assert hit["leaf"]["id"] == "BILL-CREDIT-DUP"
    assert hit["leaf"]["title"] in valid_titles(trees)


def test_trie_rejects_invented_titles():
    trie = TitleTrie(["Duplicate Charges", "Goodwill Credits"])
    assert trie.contains("Duplicate Charges") is True
    assert trie.contains("Duplicate Charges §9.9") is False
    assert trie.contains("Refund Policy") is False
    assert trie.contains("") is False


def test_section_is_retrieved_intact_not_chunked():
    trees = load_trees()
    hit = retrieve(trees, "outage service credit")
    assert hit is not None
    leaf = hit["leaf"]
    assert leaf["body"].startswith("An outage service credit of $25 is available only if")
    assert "$25" in leaf["body"] and "4 hours" in leaf["body"]
    # The whole leaf body is returned — no chunk boundary, no truncation.
    assert len(leaf["body"]) > 100


def test_answer_cites_full_section_path():
    trees = load_trees()
    result = answer(trees, "plan upgrade price premium starter")
    assert result["refused"] is False
    assert result["leaf"]["path"] == "Plan and Retention Policy > Plans > Upgrade Pricing"
    assert result["leaf"]["section"] == "§7.1"
    assert "$22.40" in result["answer"]


def test_not_found_returns_refusal_not_a_guess():
    trees = load_trees()
    result = answer(trees, "quantum entanglement warranty terms")
    assert result["refused"] is True
    assert result["leaf"] is None
    assert "Not found in policy" in result["answer"]


def test_empty_query_returns_no_leaf():
    assert retrieve(load_trees(), "") is None
    assert retrieve(load_trees(), "the and of") is None


def test_auto_toc_is_flagged_and_covers_plain_docs():
    doc = {"id": "POL-999", "title": "Plain Policy",
           "body": "First rule applies here. Second rule applies there."}
    tree = auto_toc_from_doc(doc)
    assert tree["autoGenerated"] is True
    assert len(tree["leaves"]) == 2
    assert tree["leaves"][0]["body"] == "First rule applies here."


def test_measured_eval_has_zero_invalid_sections():
    result = measure_eval(load_trees())
    assert result["total"] == 10
    assert result["invalidSections"] == 0
    assert result["invalidRate"] == 0
    # Recall is measured, not asserted at 100% — the test records it honestly.
    assert 0 <= result["recallAt1"] <= 100
    print(f"\nSTAIR measured Recall@1: {result['recallAt1']}% ({result['correct']}/10)")
